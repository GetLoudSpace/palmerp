#!/usr/bin/env node
/**
 * template-bootstrap.mjs — Bootstrap 100% para agente instalador (IA o humano)
 * Solicita datos mínimos, genera .env.local + claves, valida, provisiona y guía Vercel/Supabase/MiniPC.
 * Uso: node scripts/template-bootstrap.mjs
 *      node scripts/template-bootstrap.mjs --slug bodega-lopez --name "Bodega López S.L." --admin-email ana@bodega.es --domain bodega.palmerp.es --modes VENTAS,RESTAURANTE
 */
import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import readline from "node:readline";
import { execSync } from "node:child_process";

function randBase64() {
  return crypto.randomBytes(32).toString("base64");
}
function slugify(v) {
  return v.trim().toLowerCase().replace(/[^a-z0-9-]/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "");
}
function parseArgs() {
  const m = new Map();
  for (let i = 2; i < process.argv.length; i++) {
    const a = process.argv[i];
    if (!a.startsWith("--")) continue;
    const k = a.slice(2);
    const n = process.argv[i + 1];
    if (!n || n.startsWith("--")) { m.set(k, "true"); continue; }
    m.set(k, n); i++;
  }
  return m;
}
function ask(q, def = "") {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((res) => {
    rl.question(`${q}${def ? ` [${def}]` : ""}: `, (ans) => {
      rl.close();
      res((ans.trim() || def).trim());
    });
  });
}

async function main() {
  const args = parseArgs();
  console.log("\n=== PalmerP Template Bootstrap 100% ===\n");
  console.log("Este script te guía para dejar el template 100% operativo.\n");

  const slugRaw = args.get("slug") || await ask("Slug (ej. bodega-lopez)", process.env.PALMERA_INSTANCE_SLUG || "demo-cliente");
  const slug = slugify(slugRaw);
  if (slug.length < 3) throw new Error("Slug mínimo 3 caracteres");

  const name = args.get("name") || await ask("Nombre empresa", process.env.PALMERA_INSTANCE_NAME || "Demo Cliente S.L.");
  const adminName = args.get("admin-name") || await ask("Nombre admin", process.env.PALMERA_INSTANCE_ADMIN_NAME || "Admin");
  const adminEmail = (args.get("admin-email") || await ask("Email admin", process.env.PALMERA_INSTANCE_ADMIN_EMAIL || "admin@demo.es")).toLowerCase();
  const domain = args.get("domain") || await ask("Dominio (ej. cliente.palmerp.es o cliente.es)", process.env.PALMERA_INSTANCE_DOMAIN || `${slug}.palmerp.es`);
  const timezone = args.get("timezone") || await ask("Timezone", process.env.PALMERA_INSTANCE_TIMEZONE || "Europe/Madrid");
  const modesRaw = args.get("modes") || await ask("Modos (coma, ej. VENTAS,RESTAURANTE,EDUCACION)", process.env.PALMERA_INSTANCE_MODES || "VENTAS,RESTAURANTE");
  const modes = modesRaw.split(",").map((m) => m.trim()).filter(Boolean);

  let databaseUrl = args.get("database-url") || process.env.DATABASE_URL || "";
  if (!databaseUrl) {
    console.log("\n⚠️  Necesitas DATABASE_URL (Supabase pooler 6543 ?pgbouncer=true)");
    console.log("   Supabase → Project Settings → Database → Connection string → URI (Pooler 6543)");
    databaseUrl = await ask("DATABASE_URL (postgresql://...)", "");
  }
  if (!databaseUrl) throw new Error("DATABASE_URL requerido");

  // Generar claves si no existen
  const backupKey = process.env.BACKUP_ENCRYPTION_KEY && process.env.BACKUP_ENCRYPTION_KEY !== "change-me-32bytes-base64-44chars" ? process.env.BACKUP_ENCRYPTION_KEY : randBase64();
  const nextAuthSecret = process.env.NEXTAUTH_SECRET && !process.env.NEXTAUTH_SECRET.includes("development") ? process.env.NEXTAUTH_SECRET : randBase64();
  const cronSecret = process.env.CRON_SECRET || randBase64();
  const fleetKey = process.env.FLEET_API_KEY || randBase64();
  const adminPassword = args.get("admin-password") || process.env.PALMERA_INSTANCE_ADMIN_PASSWORD || crypto.randomBytes(12).toString("base64url");

  // Crear .env.local
  const envPath = path.join(process.cwd(), ".env.local");
  const envExamplePath = path.join(process.cwd(), ".env.example");
  let envContent = "";
  try { envContent = fs.readFileSync(envExamplePath, "utf8"); } catch { envContent = `# PalmerP env\n`; }

  // Si existe .env.local, no sobrescribir sin preguntar
  if (fs.existsSync(envPath)) {
    const ow = await ask(`Ya existe .env.local, ¿sobrescribir? (y/N)`, "N");
    if (ow.toLowerCase() !== "y") {
      console.log("Manteniendo .env.local existente.");
    } else {
      // proceed to write
    }
  }

  const shouldWrite = !fs.existsSync(envPath) || (await ask("Confirmar escritura .env.local", "y")).toLowerCase() === "y";
  // For simplicity, siempre generamos contenido fresco si shouldWrite o si no existía
  if (!fs.existsSync(envPath) || shouldWrite) {
    const out = `# === GENERATED by template-bootstrap.mjs ${new Date().toISOString()} ===
NEXTAUTH_URL="https://${domain}"
NEXTAUTH_SECRET="${nextAuthSecret}"
DATABASE_URL="${databaseUrl}"
PALMERA_PLATFORM_URL="https://${domain}"
PALMERA_INSTANCE_SLUG="${slug}"
PALMERA_INSTANCE_NAME="${name}"
PALMERA_INSTANCE_DOMAIN="${domain}"
PALMERA_INSTANCE_ADMIN_NAME="${adminName}"
PALMERA_INSTANCE_ADMIN_EMAIL="${adminEmail}"
PALMERA_INSTANCE_ADMIN_PASSWORD="${adminPassword}"
PALMERA_INSTANCE_TIMEZONE="${timezone}"
PALMERA_INSTANCE_MODES="${modes.join(",")}"
BACKUP_ENCRYPTION_KEY="${backupKey}"
BACKUP_LOCAL_DIR="/data/backups/palmerp"
# CLIENT_BACKUP_S3_* — configura luego con credenciales R2 cliente
# CLIENT_BACKUP_S3_ENDPOINT="https://<account>.r2.cloudflarestorage.com"
# CLIENT_BACKUP_S3_BUCKET="cliente-backups"
# CLIENT_BACKUP_S3_ACCESS_KEY="..."
# CLIENT_BACKUP_S3_SECRET_KEY="..."
# PALMERP_VAULT_R2_* — tu vault central
# PALMERP_VAULT_R2_ACCOUNT_ID="..."
# PALMERP_VAULT_R2_ACCESS_KEY_ID="..."
# PALMERP_VAULT_R2_SECRET_ACCESS_KEY="..."
# PALMERP_VAULT_R2_BUCKET_NAME="palmerp-vault"
CRON_SECRET="${cronSecret}"
FLEET_API_KEY="${fleetKey}"
# PALMERP_CONTROL_URL="https://control.palmerp.es"
`;

    // Si no debe escribir, no escribimos; si sí, escribimos
    const finalWrite = !fs.existsSync(envPath) || (fs.existsSync(envPath) && shouldWrite);
    if (finalWrite || !fs.existsSync(envPath)) {
      fs.writeFileSync(envPath, out, "utf8");
      console.log(`\n✅ .env.local creado: ${envPath}`);
    }
    // También crear .env para prisma local
    const envLocalContent = fs.readFileSync(envPath, "utf8");
    fs.writeFileSync(path.join(process.cwd(), ".env"), envLocalContent, "utf8");
  }

  console.log("\n--- Claves generadas (guarda en caja fuerte + papel QR) ---");
  console.log(`BACKUP_ENCRYPTION_KEY: ${backupKey}`);
  console.log(`NEXTAUTH_SECRET:       ${nextAuthSecret}`);
  console.log(`CRON_SECRET:           ${cronSecret}`);
  console.log(`FLEET_API_KEY:         ${fleetKey}`);
  console.log(`Admin password:        ${adminPassword}`);
  console.log("\n⚠️  Si pierdes BACKUP_ENCRYPTION_KEY, el .enc es irrecuperable. Imprime QR ya.\n");

  // Validaciones
  console.log("--- Validando ---");
  try {
    console.log("→ npx prisma generate ...");
    execSync("npx prisma generate", { stdio: "inherit" });
  } catch (e) { console.warn("prisma generate falló", e.message); }

  try {
    console.log("→ npx prisma migrate deploy ...");
    execSync("npx prisma migrate deploy", { stdio: "inherit" });
  } catch (e) {
    console.warn("migrate deploy falló (prueba npx prisma db push):", e.message);
    try { execSync("npx prisma db push", { stdio: "inherit" }); } catch {}
  }

  try {
    console.log("→ npm run instance:provision ...");
    const modesArg = modes.join(",");
    execSync(`node scripts/provision-instance.mjs --slug "${slug}" --name "${name}" --domain "${domain}" --admin-name "${adminName}" --admin-email "${adminEmail}" --admin-password "${adminPassword}" --timezone "${timezone}" --modes "${modesArg}"`, { stdio: "inherit" });
  } catch (e) { console.warn("provision falló (puede que tenant ya exista):", e.message); }

  try {
    console.log("→ npx tsc --noEmit --skipLibCheck ...");
    execSync("npx tsc --noEmit --skipLibCheck", { stdio: "inherit" });
    console.log("✅ tsc OK");
  } catch (e) { console.warn("tsc falló", e.message); }

  console.log("\n=== Próximos pasos 100% (no te saltes ninguno) ===\n");
  console.log("1) VERCEL: importa el fork en vercel.com → Add New Project → Import Git Repository (cliente-x)");
  console.log("   - Environment Variables (Production): pega TODAS las vars de .env.local (DATABASE_URL, NEXTAUTH_*, BACKUP_*, CRON_SECRET, FLEET_API_KEY, etc.)");
  console.log("   - Production Branch: master");
  console.log("   - Deploy → verifica https://<dominio>/api/cron/daily-backups con curl -H \"Authorization: Bearer $CRON_SECRET\" (debe dar success 3 destinos)");
  console.log("");
  console.log("2) R2 CLIENTE (destino B, 30d): crea bucket cliente-backups en Cloudflare R2 del cliente y pon CLIENT_BACKUP_S3_* en Vercel Env + .env del MiniPC");
  console.log("");
  console.log("3) R2 VAULT PALMERP (destino C, 90d): pon PALMERP_VAULT_R2_* en Vercel Env + MiniPC .env (tu cuenta, bucket palmerp-vault, inmutable)");
  console.log("");
  console.log("4) MINIPC (siempre ON):");
  console.log("   ssh mini");
  console.log("   sudo apt update && sudo apt install -y nodejs postgresql-client git");
  console.log("   git clone <repo-cliente> /opt/palmerp && cd /opt/palmerp && npm ci --legacy-peer-deps && cp .env.example .env && nano .env  # pega mismas vars");
  console.log("   npm run backup:agent  # debe crear /data/backups/palmerp/.../*.enc y subir a B y C");
  console.log("   sudo cp scripts/systemd/palmerp-backup.* /etc/systemd/system/ && sudo systemctl daemon-reload && sudo systemctl enable --now palmerp-backup.timer");
  console.log("");
  console.log("5) VERIFICACIÓN (antes de entregar):");
  console.log("   npx tsc --noEmit --skipLibCheck && npm run build && ./init.sh  # todo [OK]");
  console.log("   curl -H \"Authorization: Bearer $CRON_SECRET\" https://<dominio>/api/cron/daily-backups | jq .summary  # success 1");
  console.log("   curl -H \"Authorization: Bearer $FLEET_API_KEY\" https://control.palmerp.es/api/fleet/backup-heartbeat | jq .status  # verde <24h");
  console.log("");
  console.log("6) HANDOVER: entrega al cliente docs/Manual-PalmerP-Triple-Backup-Fleet.pdf + QR de BACKUP_ENCRYPTION_KEY + accesos Vercel/Supabase/GitHub");
  console.log("");
  console.log("📖 Guía completa: docs/TEMPLATE-INSTALADOR.md");
  console.log("📄 Manual dueño: docs/Manual-PalmerP-Triple-Backup-Fleet.pdf");
  console.log("\n✅ Bootstrap completado. Sigue los pasos 1-6 y marca checklist §15 de TEMPLATE-INSTALADOR.md\n");
}

main().catch((e) => { console.error(e); process.exit(1); });
